"""Write app/jungle/jungle_fx_tables.inc: the effect tables the firmware
cannot compute itself (its libc has no floating-point maths).

  eq_coef     4 bands x 25 gains (-12..+12 dB) x {b0, b1, b2, a1, a2}, Q28,
              RBJ cookbook biquads at 44.1 kHz: low shelf 100 Hz, peaks at
              500 Hz and 2.5 kHz (Q 1), high shelf 8 kHz (shelf slope 1)
  db_gain     linear gain in Q12 for -48..+24 dB in half-dB steps
  level_db    level of an envelope index i (0..255, linear, 256 = full
              scale) in half-dB, for the compressor's gain curve

Usage: python -I tools/jungle/make_fx_tables.py [out.inc]
"""
import math
import sys
from pathlib import Path

FS = 44100.0
out = Path(sys.argv[1]) if len(sys.argv) > 1 else \
    Path(__file__).resolve().parents[2] / 'app' / 'jungle' / 'jungle_fx_tables.inc'


def shelf(f0, gain_db, high):
    a = 10 ** (gain_db / 40)
    w = 2 * math.pi * f0 / FS
    cw, sw = math.cos(w), math.sin(w)
    alpha = sw / 2 * math.sqrt((a + 1 / a) * (1 / 1.0 - 1) + 2)
    sa = 2 * math.sqrt(a) * alpha
    if not high:
        b0 = a * ((a + 1) - (a - 1) * cw + sa)
        b1 = 2 * a * ((a - 1) - (a + 1) * cw)
        b2 = a * ((a + 1) - (a - 1) * cw - sa)
        a0 = (a + 1) + (a - 1) * cw + sa
        a1 = -2 * ((a - 1) + (a + 1) * cw)
        a2 = (a + 1) + (a - 1) * cw - sa
    else:
        b0 = a * ((a + 1) + (a - 1) * cw + sa)
        b1 = -2 * a * ((a - 1) + (a + 1) * cw)
        b2 = a * ((a + 1) + (a - 1) * cw - sa)
        a0 = (a + 1) - (a - 1) * cw + sa
        a1 = 2 * ((a - 1) - (a + 1) * cw)
        a2 = (a + 1) - (a - 1) * cw - sa
    return [b0 / a0, b1 / a0, b2 / a0, a1 / a0, a2 / a0]


def peak(f0, gain_db, q):
    a = 10 ** (gain_db / 40)
    w = 2 * math.pi * f0 / FS
    alpha = math.sin(w) / (2 * q)
    cw = math.cos(w)
    a0 = 1 + alpha / a
    return [(1 + alpha * a) / a0, -2 * cw / a0, (1 - alpha * a) / a0, -2 * cw / a0, (1 - alpha / a) / a0]


bands = [lambda g: shelf(100, g, False), lambda g: peak(500, g, 1.0),
         lambda g: peak(2500, g, 1.0), lambda g: shelf(8000, g, True)]
lines = [
    '/* SPDX-License-Identifier: GPL-3.0-only WITH GPL-3.0-linking-exception */',
    '/* Generated by tools/jungle/make_fx_tables.py. Do not edit. */',
    '',
    '/* EQ: [band][gain + 12][b0, b1, b2, a1, a2], Q28. */',
    'static const int32_t eq_coef[4][25][5] = {',
]
for band in bands:
    lines.append('    {')
    for g in range(-12, 13):
        c = band(g)
        lines.append('        {' + ', '.join(str(round(v * (1 << 28))) for v in c) + '},')
    lines.append('    },')
lines.append('};')
lines.append('')
lines.append('/* Gain for -48..+24 dB in half-dB steps (index = 2 * dB + 96), Q12. */')
gains = [round(4096 * 10 ** ((i / 2 - 48) / 20)) for i in range(145)]
lines.append('static const uint16_t db_gain[145] = {')
for i in range(0, 145, 12):
    lines.append('    ' + ', '.join(str(v) for v in gains[i:i + 12]) + ',')
lines.append('};')
lines.append('')
lines.append('/* Level of envelope index i (linear, 256 = full scale) in half-dB. */')
levels = [-120] + [round(2 * 20 * math.log10(i / 256)) for i in range(1, 256)]
lines.append('static const int16_t level_db[256] = {')
for i in range(0, 256, 16):
    lines.append('    ' + ', '.join(str(v) for v in levels[i:i + 16]) + ',')
lines.append('};')
lines.append('')
out.write_text('\n'.join(lines), encoding='ascii', newline='\n')
print(f'wrote {out}')
